#!/bin/sh
set -e

: "${PUBLIC_BACKEND_URL:?请在容器环境变量中设置 PUBLIC_BACKEND_URL}"
: "${PUBLIC_TRAEFIK_URL:?请在容器环境变量中设置 PUBLIC_TRAEFIK_URL}"
PUBLIC_KNOWLEDGE_CONFIG_TIMEOUT_MS="${PUBLIC_KNOWLEDGE_CONFIG_TIMEOUT_MS:-8000}"
PUBLIC_KNOWLEDGE_READ_TIMEOUT_MS="${PUBLIC_KNOWLEDGE_READ_TIMEOUT_MS:-15000}"
PUBLIC_KNOWLEDGE_WRITE_TIMEOUT_MS="${PUBLIC_KNOWLEDGE_WRITE_TIMEOUT_MS:-30000}"
PUBLIC_DOCS_URL="${PUBLIC_DOCS_URL:-}"
PUBLIC_DOCS_URL_JS=$(printf '%s' "$PUBLIC_DOCS_URL" | sed 's/\\/\\\\/g; s/"/\\"/g')
PUBLIC_WEBSEARCH_URL="${PUBLIC_TRAEFIK_URL}/ws-api"
PUBLIC_TRAEFIK_FORWARDED_HOST=$(echo "$PUBLIC_TRAEFIK_URL" | sed 's|.*://||' | sed 's|/.*||')
export PUBLIC_BACKEND_URL PUBLIC_TRAEFIK_URL PUBLIC_WEBSEARCH_URL PUBLIC_TRAEFIK_FORWARDED_HOST PUBLIC_DOCS_URL
export PUBLIC_KNOWLEDGE_CONFIG_TIMEOUT_MS PUBLIC_KNOWLEDGE_READ_TIMEOUT_MS PUBLIC_KNOWLEDGE_WRITE_TIMEOUT_MS

case "$PUBLIC_WEBSEARCH_URL" in
  http://*|https://*) ;;
  *) echo "PUBLIC_WEBSEARCH_URL 必须以 http:// 或 https:// 开头，当前值：$PUBLIC_WEBSEARCH_URL" >&2; exit 1 ;;
esac
case "$PUBLIC_KNOWLEDGE_CONFIG_TIMEOUT_MS" in *[!0-9]*|"") echo "PUBLIC_KNOWLEDGE_CONFIG_TIMEOUT_MS 必须是正整数毫秒数，当前值：$PUBLIC_KNOWLEDGE_CONFIG_TIMEOUT_MS" >&2; exit 1 ;; esac
case "$PUBLIC_KNOWLEDGE_READ_TIMEOUT_MS" in *[!0-9]*|"") echo "PUBLIC_KNOWLEDGE_READ_TIMEOUT_MS 必须是正整数毫秒数，当前值：$PUBLIC_KNOWLEDGE_READ_TIMEOUT_MS" >&2; exit 1 ;; esac
case "$PUBLIC_KNOWLEDGE_WRITE_TIMEOUT_MS" in *[!0-9]*|"") echo "PUBLIC_KNOWLEDGE_WRITE_TIMEOUT_MS 必须是正整数毫秒数，当前值：$PUBLIC_KNOWLEDGE_WRITE_TIMEOUT_MS" >&2; exit 1 ;; esac

cat > /usr/share/nginx/html/runtime-config.js <<EOF
window.__NINECLAW_CONFIG__ = {
  API_BASE_URL: "",
  DEFAULT_TENANT_ID: "default",
  TRAEFIK_URL: "",
  WEBSEARCH_URL: "/ws-api",
  DOCS_URL: "${PUBLIC_DOCS_URL_JS}",
  KNOWLEDGE_CONFIG_TIMEOUT_MS: ${PUBLIC_KNOWLEDGE_CONFIG_TIMEOUT_MS},
  KNOWLEDGE_READ_TIMEOUT_MS: ${PUBLIC_KNOWLEDGE_READ_TIMEOUT_MS},
  KNOWLEDGE_WRITE_TIMEOUT_MS: ${PUBLIC_KNOWLEDGE_WRITE_TIMEOUT_MS}
};
EOF

envsubst '$PUBLIC_BACKEND_URL $PUBLIC_TRAEFIK_URL $PUBLIC_WEBSEARCH_URL $PUBLIC_TRAEFIK_FORWARDED_HOST' \
  < /etc/nginx/templates/nginx.conf.template \
  > /etc/nginx/conf.d/default.conf

exec nginx -g "daemon off;"
